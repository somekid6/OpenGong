"""PlatformIO pre-build script: gzip src/receiver/web/index.html into src/receiver/web_page.h.

Runs automatically before each receiver build (see extra_scripts in platformio.ini).
The header is regenerated only when the page changes, so unchanged builds stay incremental.
"""
import gzip
import hashlib
import os

Import("env")  # noqa: F821  (SCons global provided by PlatformIO)

SRC_DIR = os.path.join(env.subst("$PROJECT_SRC_DIR"), "receiver")
SRC = os.path.join(SRC_DIR, "web", "index.html")
DST = os.path.join(SRC_DIR, "web_page.h")


def build_header() -> None:
    with open(SRC, "rb") as f:
        html = f.read()
    digest = hashlib.sha1(html).hexdigest()

    if os.path.exists(DST):
        with open(DST, "r", encoding="utf-8") as f:
            if ("// sha1 " + digest) in f.read(2048):
                return  # already up to date

    gz = gzip.compress(html, compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(gz), 24):
        rows.append("  " + ", ".join("0x%02x" % b for b in gz[i : i + 24]) + ",")

    lines = [
        "// Generated by tools/embed_web.py from src/receiver/web/index.html. Do not edit.",
        "// sha1 " + digest + " of the source page; gzip %d -> %d bytes" % (len(html), len(gz)),
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include <pgmspace.h>",
        "",
        "constexpr size_t kIndexHtmlGzLen = %d;" % len(gz),
        "const uint8_t kIndexHtmlGz[] PROGMEM = {",
        *rows,
        "};",
        "",
    ]
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("embed_web: %s -> %s (%d bytes gzipped)" % (os.path.relpath(SRC), os.path.relpath(DST), len(gz)))


build_header()
